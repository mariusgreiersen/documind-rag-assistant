"""Run the evaluation benchmark against the configured pipeline.

    python -m documind.evaluation.run              retrieval metrics + relevance-gate calibration
    python -m documind.evaluation.run --answers    also generate answers with the configured LLM

Results are written to evals/results/. Answer evaluation calls the configured
LLM provider once per question (plus nothing else); it is skipped with a clear
message when no provider is configured.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from documind.core.config import REPO_ROOT, get_settings
from documind.core.logging import configure_logging
from documind.evaluation.dataset import DEFAULT_DATASET, load_cases
from documind.evaluation.harness import (
    KS,
    AnswerRow,
    RetrievalConfig,
    RetrievalRow,
    as_dicts,
    environment_info,
    eval_workspace,
    evaluate_answers,
    evaluate_retrieval,
    gate_sweep,
    locate,
    random_baseline,
    summarize_answers,
    summarize_retrieval,
)
from documind.generation.llm_provider import build_llm_provider

RESULTS_DIR = REPO_ROOT / "evals" / "results"
THRESHOLDS = [round(0.05 * i, 2) for i in range(0, 19)]


def fmt(value: Any) -> str:
    return f"{value:.3f}" if isinstance(value, float) else str(value)


def retrieval_markdown(
    cfg: RetrievalConfig,
    summary: dict[str, Any],
    rows: Sequence[RetrievalRow],
    sweep: list[dict[str, Any]],
    env: dict[str, str],
    ingest_s: float,
    chunks: int,
    threshold: float,
) -> str:
    lines = [
        "# Retrieval evaluation (baseline)",
        "",
        "Generated by `python -m documind.evaluation.run`. All numbers below were measured by that command; nothing is hand-edited.",
        "",
        "## Configuration",
        "",
        f"- Embedding model: `{cfg.embedding_model}`" + (f" (query prefix `{cfg.query_prefix}`)" if cfg.query_prefix else ""),
        f"- Chunking: {cfg.chunk_size} tokens, {cfg.chunk_overlap} overlap, min {cfg.min_chunk_tokens} (embedding-model tokenizer)",
        f"- Corpus: bundled demo documents, {chunks} chunks; indexing took {ingest_s:.1f} s",
        f"- Questions: {summary['questions_total']} ({summary['questions_answerable']} answerable)",
        f"- Environment: Python {env['python']}, {env['platform']}, sentence-transformers {env['sentence_transformers']}, chromadb {env['chromadb']}, torch {env['torch']}",
        f"- Run at: {env['timestamp_utc']}",
        "",
        "## Retrieval metrics (answerable questions)",
        "",
        "| K | Hit@K (any relevant) | Random Hit@K | Evidence recall@K (all evidence) | Precision@K |",
        "|---|---|---|---|---|",
    ]
    rnd = summary["random_baseline"]
    for k in KS:
        lines.append(
            f"| {k} | {fmt(summary[f'hit@{k}'])} | {fmt(rnd[f'random_hit@{k}'])} | {fmt(summary[f'evidence_recall@{k}'])} | "
            f"{fmt(summary[f'precision@{k}'])} |"
        )
    lines += [
        "",
        f"*Random Hit@K* is the expected Hit@K if the {rnd['corpus_chunks']} chunks were ranked at random. The corpus is small, "
        "so Hit@5 and Hit@10 are easy to achieve; Hit@1 and MRR are the more informative ranking measures here.",
        "",
        f"- **MRR@10:** {fmt(summary['mrr@10'])}",
        f"- **Full evidence coverage@5** (every required passage in the top 5): {fmt(summary['full_coverage@5'])}",
        "",
        "## By category",
        "",
        "| Category | n | Hit@5 | Evidence recall@5 | MRR@10 |",
        "|---|---|---|---|---|",
    ]
    for cat, m in summary["by_category"].items():
        lines.append(f"| {cat} | {m['n']} | {fmt(m['hit@5'])} | {fmt(m['evidence_recall@5'])} | {fmt(m['mrr@10'])} |")
    lines += [
        "",
        "## Relevance gate calibration",
        "",
        f"Answerability decided **only** by the top-1 cosine similarity (no LLM). The configured `MIN_RELEVANCE_SCORE` is **{threshold}**.",
        "",
        "| Threshold | Answerable passed | Unanswerable rejected | Accuracy |",
        "|---|---|---|---|",
    ]
    for s in sweep:
        marker = " ←" if abs(s["threshold"] - threshold) < 1e-9 else ""
        lines.append(f"| {s['threshold']:.2f}{marker} | {s['answerable_passed']} | {s['unanswerable_rejected']} | {s['accuracy']:.3f} |")
    lines += [
        "",
        "## Per-question results",
        "",
        "| ID | Category | Top-1 score | First relevant rank | Evidence covered@5 |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        first = next((i for i, rel in enumerate(r.relevant, 1) if rel), None)
        covered = len(set().union(*[set(m) for m in r.evidence_matches[:5]])) if r.answerable else None
        lines.append(
            f"| {r.case_id} | {r.category} | {fmt(r.top_score)} | {(first or 'miss') if r.answerable else 'n/a'}"
            f" | {f'{covered}/{r.n_evidence}' if r.answerable else 'n/a'} |"
        )
    return "\n".join(lines) + "\n"


def answers_markdown(summary: dict[str, Any], rows: Sequence[AnswerRow], provider: str, model: str, env: dict[str, str]) -> str:
    lines = [
        "# Answer evaluation",
        "",
        f"Provider `{provider}`, model `{model}`, run at {env['timestamp_utc']}. Generated by `python -m documind.evaluation.run --answers`.",
        "",
        "Deterministic checks only. *Key-fact recall* is a keyword heuristic and *cited-evidence precision* checks that a",
        "cited passage overlaps the annotated evidence; neither proves that every sentence is supported. The",
        "*Reviewer verdict* column is for manual groundedness review.",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
    ]
    for key, value in summary.items():
        lines.append(f"| {key} | {fmt(value)} |")
    lines += ["", "## Answers for manual review", ""]
    for r in rows:
        cites = (
            ", ".join(f"[{c['n']}] {c['title']} p.{c['page']}{'' if c['relevant'] else ' (not annotated evidence)'}" for c in r.citations)
            or "none"
        )
        lines += [
            f"### {r.case_id} ({r.category}) — status `{r.status}`",
            "",
            (r.answer or "_no answer_").strip(),
            "",
            f"- Citations: {cites}",
            f"- Rejected citation IDs: {', '.join(r.rejected_citation_ids) or 'none'}",
            f"- Key-fact recall (heuristic): {fmt(r.key_fact_recall) if r.key_fact_recall is not None else 'n/a'}",
            f"- Forbidden phrases present: {', '.join(r.forbidden_hit) or 'none'}",
            "- Reviewer verdict: _not yet reviewed_",
            "",
        ]
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m documind.evaluation.run")
    parser.add_argument("--dataset", type=Path, default=DEFAULT_DATASET)
    parser.add_argument("--out", type=Path, default=RESULTS_DIR)
    parser.add_argument("--answers", action="store_true", help="also evaluate generated answers (requires an LLM provider)")
    args = parser.parse_args(argv)

    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(encoding="utf-8")  # type: ignore[union-attr]
    configure_logging("WARNING", "text")
    settings = get_settings()
    cases = load_cases(args.dataset)
    spans = locate(cases, settings)
    cfg = RetrievalConfig.from_settings(settings, "baseline")
    env = environment_info()
    args.out.mkdir(parents=True, exist_ok=True)

    llm = build_llm_provider(settings) if args.answers else None
    if args.answers and llm is None:
        print("Answer evaluation skipped: no LLM provider is configured (set LLM_API_KEY). Retrieval metrics are still computed.")

    with eval_workspace(cfg, settings, llm=llm) as (container, ingest_s):
        chunk_total = container.store.count()
        rows = evaluate_retrieval(container, cases, spans)
        summary = summarize_retrieval(rows)
        summary["random_baseline"] = random_baseline(container, cases, spans)
        sweep = gate_sweep(rows, THRESHOLDS)
        answer_rows = evaluate_answers(container, cases, spans) if llm is not None else None

    payload = {
        "config": cfg.__dict__,
        "environment": env,
        "corpus_chunks": chunk_total,
        "ingest_seconds": round(ingest_s, 2),
        "summary": summary,
        "gate_sweep": sweep,
        "min_relevance_score": settings.min_relevance_score,
        "rows": as_dicts(rows),
    }
    (args.out / "retrieval_baseline.json").write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8", newline="\n")
    (args.out / "retrieval_baseline.md").write_text(
        retrieval_markdown(cfg, summary, rows, sweep, env, ingest_s, chunk_total, settings.min_relevance_score),
        encoding="utf-8",
        newline="\n",
    )

    print(f"Evaluated {summary['questions_total']} questions ({summary['questions_answerable']} answerable) on {chunk_total} chunks")
    for k in KS:
        print(
            f"  Hit@{k:<2} {summary[f'hit@{k}']:.3f}   Evidence recall@{k:<2} {summary[f'evidence_recall@{k}']:.3f}   Precision@{k:<2} {summary[f'precision@{k}']:.3f}"
        )
    print(f"  MRR@10 {summary['mrr@10']:.3f}")
    current = next((s for s in sweep if abs(s["threshold"] - settings.min_relevance_score) < 1e-9), None)
    if current:
        print(
            f"  Relevance gate @ {settings.min_relevance_score}: {current['answerable_passed']} answerable passed, {current['unanswerable_rejected']} unanswerable rejected"
        )

    if answer_rows is not None and llm is not None:
        a_summary = summarize_answers(answer_rows)
        stem = f"answers_{llm.name}"
        (args.out / f"{stem}.json").write_text(
            json.dumps(
                {"provider": llm.name, "model": llm.model, "environment": env, "summary": a_summary, "rows": as_dicts(answer_rows)},
                indent=2,
            )
            + "\n",
            encoding="utf-8",
            newline="\n",
        )
        (args.out / f"{stem}.md").write_text(
            answers_markdown(a_summary, answer_rows, llm.name, llm.model, env), encoding="utf-8", newline="\n"
        )
        print("Answer evaluation:")
        for key, value in a_summary.items():
            print(f"  {key}: {fmt(value)}")
    print(f"Reports written to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
